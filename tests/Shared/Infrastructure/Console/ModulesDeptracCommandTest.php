declare(strict_types=1);

namespace App\Tests\Shared\Infrastructure\Console;

use App\Shared\Infrastructure\Console\ModulesDeptracCommand;
use App\Shared\Infrastructure\Module\DeptracModulesConfig;
use App\Shared\Infrastructure\Module\InstalledModules;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\ArrayInput;
use Symfony\Component\Console\Output\BufferedOutput;
use Symfony\Component\Console\Style\SymfonyStyle;

/**
 * The generated module-level Deptrac file is written from the manifests, and
 * the check fails while the committed file is stale.
 */
final class ModulesDeptracCommandTest extends TestCase
{
    private string $file;

    protected function setUp(): void
    {
        $this->file = sys_get_temp_dir().'/deptrac-modules-'.bin2hex(random_bytes(4)).'.yaml';
    }

    protected function tearDown(): void
    {
        if (is_file($this->file)) {
            unlink($this->file);
        }
    }

    public function testCheckFailsOnStaleFile(): void
    {
        file_put_contents($this->file, "# stale\n");
        $output = new BufferedOutput();

        $status = $this->command()($this->io($output), check: true, file: $this->file);

        self::assertSame(Command::FAILURE, $status);
        self::assertStringContainsString('app:modules:deptrac', $output->fetch());
        self::assertSame("# stale\n", file_get_contents($this->file));
    }

    public function testCheckFailsOnMissingFile(): void
    {
        $status = $this->command()($this->io(new BufferedOutput()), check: true, file: $this->file);

        self::assertSame(Command::FAILURE, $status);
    }

    public function testCheckPassesAfterWrite(): void
    {
        self::assertSame(Command::SUCCESS, $this->command()($this->io(new BufferedOutput()), file: $this->file));
        self::assertStringStartsWith('# Generated by bin/console app:modules:deptrac.', (string) file_get_contents($this->file));

        self::assertSame(Command::SUCCESS, $this->command()($this->io(new BufferedOutput()), check: true, file: $this->file));
    }

    public function testCommittedFileIsCurrent(): void
    {
        self::assertSame(Command::SUCCESS, $this->command()($this->io(new BufferedOutput()), check: true));
    }

    private function command(): ModulesDeptracCommand
    {
        $projectDir = \dirname(__DIR__, 4);

        return new ModulesDeptracCommand(new InstalledModules($projectDir), new DeptracModulesConfig(), $projectDir);
    }

    private function io(BufferedOutput $output): SymfonyStyle
    {
        return new SymfonyStyle(new ArrayInput([]), $output);
    }
}
