declare(strict_types=1);

namespace App\Tests\Shared\Infrastructure\Module;

use App\Shared\Domain\Module\ModuleGraph;
use App\Shared\Domain\Module\ModuleId;
use App\Shared\Domain\Module\ModuleKind;
use App\Shared\Domain\Module\ModuleManifest;
use App\Shared\Infrastructure\Module\DeptracModulesConfig;
use PHPUnit\Framework\TestCase;

/**
 * One Deptrac layer per module; a module may use the modules its manifest
 * declares, nothing else.
 */
final class DeptracModulesConfigTest extends TestCase
{
    private const string EXPECTED = <<<'YAML'
        # Generated by bin/console app:modules:deptrac. Do not edit.
        deptrac:
          paths:
            - src
          layers:
            - name: invoicing
              collectors:
                - type: classLike
                  value: ^App\\Invoicing\\.*
            - name: shared
              collectors:
                - type: classLike
                  value: ^App\\Shared\\.*
            - name: timesheet
              collectors:
                - type: classLike
                  value: ^App\\Timesheet\\.*
            - name: work
              collectors:
                - type: classLike
                  value: ^App\\Work\\.*
          ruleset:
            invoicing:
              - shared
            shared: []
            timesheet:
              - invoicing
              - work
            work:
              - shared

        YAML;

    public function testRendersOneLayerPerModule(): void
    {
        self::assertSame(self::EXPECTED, new DeptracModulesConfig()->render(new ModuleGraph($this->modules())));
    }

    public function testOutputIsStable(): void
    {
        self::assertSame(self::EXPECTED, new DeptracModulesConfig()->render(new ModuleGraph(array_reverse($this->modules()))));
    }

    public function testAbsentOptionalModuleIsNotAllowed(): void
    {
        $graph = new ModuleGraph([
            $this->module('shared', ModuleKind::Core, 'Shared'),
            $this->module('work', ModuleKind::Module, 'Work', requires: ['shared'], optional: ['invoicing']),
        ]);

        self::assertStringNotContainsString('invoicing', new DeptracModulesConfig()->render($graph));
    }

    public function testHyphenatedIdsBecomeUnderscoredLayers(): void
    {
        // Deptrac reads the ruleset through Symfony Config, which turns "-" in keys into "_".
        $graph = new ModuleGraph([
            $this->module('exchange-rate', ModuleKind::Module, 'ExchangeRate', requires: ['shared']),
            $this->module('purchasing', ModuleKind::Module, 'Purchasing', requires: ['exchange-rate']),
            $this->module('shared', ModuleKind::Core, 'Shared'),
        ]);
        $config = new DeptracModulesConfig()->render($graph);

        self::assertStringContainsString("    - name: exchange_rate\n", $config);
        self::assertStringContainsString("    exchange_rate:\n      - shared\n", $config);
        self::assertStringContainsString("    purchasing:\n      - exchange_rate\n", $config);
        self::assertStringNotContainsString('exchange-rate', $config);
    }

    /**
     * @return list<ModuleManifest>
     */
    private function modules(): array
    {
        return [
            $this->module('shared', ModuleKind::Core, 'Shared'),
            $this->module('work', ModuleKind::Module, 'Work', requires: ['shared']),
            $this->module('timesheet', ModuleKind::Module, 'Timesheet', requires: ['work'], optional: ['invoicing']),
            $this->module('invoicing', ModuleKind::Module, 'Invoicing', requires: ['shared']),
        ];
    }

    /**
     * @param list<string> $requires
     * @param list<string> $optional
     */
    private function module(string $id, ModuleKind $kind, string $directory, array $requires = [], array $optional = []): ModuleManifest
    {
        return new ModuleManifest(
            ModuleId::of($id),
            $kind,
            'foresi/'.$id,
            'App\\'.$directory.'\\',
            array_map(ModuleId::of(...), $requires),
            array_map(ModuleId::of(...), $optional),
        );
    }
}
