/**
 * A deal's documents: {{ deal.* }} fills a template with the deal's lines and
 * its value, and "New document" on the deal's page opens the dialog of
 * Documents with the deal and its client linked, the document then listed in
 * the deal's Documents section.
 */
final class SalesDocumentsIntegrationTest extends SalesScreenTestCase
{
    public function testDealVariablesRenderLinesAndTotals(): void
    {
        $deal = $this->newDeal('Roof audit');
        $this->actAsOwner();
        // Generated by a request in the language of the person; here outside one.
        self::getContainer()->get(LocaleSwitcher::class)->setLocale('en');
        $lines = self::getContainer()->get(DealLineWrites::class);
        $lines->add(new AddDealLineInput($deal->id(), name: 'Audit', unit: 'piece', quantity: '1', unitPrice: '12000.00', currency: 'CZK'));
        $lines->add(new AddDealLineInput($deal->id(), name: 'Maintenance', unit: 'month', quantity: '1', unitPrice: '1500.00', currency: 'CZK', billingKind: 'recurring', recurrenceUnit: 'month', interval: 1));
        $lines->add(new AddDealLineInput($deal->id(), name: 'Support', unit: 'hour', quantity: '2', unitPrice: '50.00', currency: 'EUR', billingKind: 'recurring', recurrenceUnit: 'week', interval: 1, cycles: 12));
        $lines->add(new AddDealLineInput($deal->id(), name: 'Site visit', unit: '', quantity: '1.5'));
        $lines->add(new AddDealLineInput($deal->id(), name: 'Changes', unit: 'h', quantity: '40', unitPrice: '1200.00', currency: 'CZK', billingKind: 'time_based'));
        $lines->add(new AddDealLineInput($deal->id(), name: 'Advice', unit: 'h', unitPrice: '900.00', currency: 'CZK', billingKind: 'time_based'));

        $values = self::getContainer()->get(DocumentVariables::class)->values([new RecordLink('contact', $this->company->id()), new RecordLink('deal', $deal->id())]);

        $nbsp = "\u{a0}";
        self::assertSame([
            'title' => 'Roof audit',
            'owner' => 'Example Company',
            'stage' => 'Proposal',
            'status' => 'Open',
            'lines' => [
                ['name' => 'Audit', 'unit' => 'piece', 'quantity' => '1', 'unit_price' => '12,000.00'.$nbsp.'Kč', 'billing_period' => 'One-off'],
                ['name' => 'Maintenance', 'unit' => 'month', 'quantity' => '1', 'unit_price' => '1,500.00'.$nbsp.'Kč', 'billing_period' => 'Every month, no end'],
                ['name' => 'Support', 'unit' => 'hour', 'quantity' => '2', 'unit_price' => '50.00'.$nbsp.'EUR', 'billing_period' => 'Every week, 12 times'],
                ['name' => 'Site visit', 'unit' => '', 'quantity' => '1.5', 'unit_price' => '', 'billing_period' => 'One-off'],
                ['name' => 'Changes', 'unit' => 'h', 'quantity' => '40', 'unit_price' => '1,200.00'.$nbsp.'Kč', 'billing_period' => 'Hourly'],
                ['name' => 'Advice', 'unit' => 'h', 'quantity' => '', 'unit_price' => '900.00'.$nbsp.'Kč', 'billing_period' => 'Hourly'],
            ],
            'one_off_totals' => [['currency' => 'CZK', 'amount' => '12,000.00'.$nbsp.'Kč']],
            // 2 × 50 EUR every week is 100 × 52 / 12 a month, so the monthly totals are approximate.
            'monthly_totals' => [['currency' => 'CZK', 'amount' => '≈ 1,500.00'.$nbsp.'Kč'], ['currency' => 'EUR', 'amount' => '≈ 433.33'.$nbsp.'EUR']],
            'hourly_lines' => [
                ['name' => 'Changes', 'rate' => '1,200.00'.$nbsp.'Kč', 'expected_hours' => '40', 'expected_amount' => '48,000.00'.$nbsp.'Kč'],
                ['name' => 'Advice', 'rate' => '900.00'.$nbsp.'Kč', 'expected_hours' => '', 'expected_amount' => ''],
            ],
        ], $values['deal'] ?? null);
        self::assertSame('Alpha Example s.r.o.', $values['client']['name'] ?? null);

        $html = new TemplateRenderer()->render(
            '<h1>{{ deal.title }} for {{ client.name }}</h1>'
            .'{% for line in deal.lines %}<p>{{ line.name }}: {{ line.quantity }} {{ line.unit }} × {{ line.unit_price|default("–") }}, {{ line.billing_period }}</p>{% endfor %}'
            .'{% for total in deal.one_off_totals %}<p>Once {{ total.amount }}</p>{% endfor %}'
            .'{% for total in deal.monthly_totals %}<p>Monthly {{ total.amount }}</p>{% endfor %}',
            $values,
        );

        self::assertSame(str_replace('_', $nbsp, '<h1>Roof audit for Alpha Example s.r.o.</h1>'
            .'<p>Audit: 1 piece × 12,000.00_Kč, One-off</p><p>Maintenance: 1 month × 1,500.00_Kč, Every month, no end</p>'
            .'<p>Support: 2 hour × 50.00_EUR, Every week, 12 times</p><p>Site visit: 1.5  × –, One-off</p>'
            .'<p>Changes: 40 h × 1,200.00_Kč, Hourly</p><p>Advice:  h × 900.00_Kč, Hourly</p>'
            .'<p>Once 12,000.00_Kč</p><p>Monthly ≈ 1,500.00_Kč</p><p>Monthly ≈ 433.33_EUR</p>'), $html);
    }

    public function testNewDocumentFromDealLinksDealAndClient(): void
    {
        $deal = $this->newDeal('Roof audit', [0]);
        $type = new DocumentType('NDA', 'nda', true, SignatureLevel::Simple, new \DateTimeImmutable());
        $template = new DocumentTemplate($type, 'NDA, English', new \DateTimeImmutable());
        $this->em()->persist($type);
        $this->em()->persist($template);
        $this->em()->persist(new TemplateVersion($template, 1, '<h1>NDA about {{ deal.title }} with {{ client.name }}</h1>', new PageSettings(), new \DateTimeImmutable()));
        $this->em()->flush();

        $crawler = $this->client->request('GET', '/sales/deals/'.$deal->id());
        self::assertResponseIsSuccessful();
        $action = $crawler->filter('[data-deal-action="new-document"]');
        self::assertCount(1, $action);
        self::assertSame('New document', trim($action->text()));
        self::assertNotNull($action->attr('data-dialog'));
        $href = (string) $action->attr('href');
        self::assertSame('/documents/new?link_kind=deal&link_id='.$deal->id().'&links%5B0%5D=contact:'.$this->company->id(), $href);
        // The documents are a tab of their own, loaded only when it is chosen.
        self::assertCount(0, $crawler->filter('turbo-frame#deal-section-documents'));
        self::assertCount(1, $crawler->filter('[data-more-actions-menu] [data-deal-action="new-document"]'));
        $crawler = $this->client->request('GET', '/sales/deals/'.$deal->id().'?tab=documents');
        self::assertResponseIsSuccessful();
        self::assertSame(['Documents'], $crawler->filter('[data-deal-tabs] nav a[aria-current="page"]')->each(static fn (Crawler $tab): string => trim($tab->text())));
        $section = $crawler->filter('[data-deal-section="documents"] turbo-frame#deal-section-documents');
        self::assertSame('/documents/for/deal/'.$deal->id(), $section->attr('src'));
        self::assertSame('lazy', $section->attr('loading'));

        $crawler = $this->client->request('GET', $href, server: [self::DIALOG => '1']);
        self::assertResponseIsSuccessful();
        self::assertSame(['Roof audit', 'Alpha Example s.r.o.'], $crawler->filter('#document-form [data-document-link] [data-document-link-label]')->each(static fn (Crawler $node): string => $node->text()));
        $values = $crawler->filter('#document-form')->form()->getPhpValues();
        $this->client->request('POST', '/documents/new', ['typeId' => $type->id(), 'templateId' => $template->id(), 'title' => 'NDA with Alpha Example'] + $values, server: [self::DIALOG => '1']);
        self::assertResponseIsSuccessful();

        $document = $this->em()->getRepository(Document::class)->findOneBy(['title' => 'NDA with Alpha Example']);
        self::assertInstanceOf(Document::class, $document);
        $pairs = array_map(static fn (DocumentLink $link): string => $link->kind().':'.$link->targetId(), $this->em()->getRepository(DocumentLink::class)->findBy(['document' => $document]));
        sort($pairs);
        $expected = ['contact:'.$this->company->id(), 'deal:'.$deal->id()];
        sort($expected);
        self::assertSame($expected, $pairs);

        // The document shows the deal as a link to its page, and the deal's section lists the document.
        $crawler = $this->client->request('GET', '/documents/'.$document->id());
        self::assertCount(1, $crawler->filter('[data-document-links] a[href="/sales/deals/'.$deal->id().'"]'));
        $this->client->request('GET', '/documents/for/deal/'.$deal->id(), server: ['HTTP_TURBO_FRAME' => 'deal-section-documents']);
        self::assertResponseIsSuccessful();
        self::assertSelectorTextContains('turbo-frame#deal-section-documents [data-record-documents]', 'NDA with Alpha Example');
    }
}
