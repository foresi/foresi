declare(strict_types=1);

namespace Foresi\Mail\Application;

/**
 * Runs a change in one database transaction, joining the one already open, and
 * flushes the entities it touched before it commits.
 */
interface MailTransaction
{
    /**
     * @template T
     *
     * @param callable(): T $work
     *
     * @return T
     */
    public function run(callable $work): mixed;
}
